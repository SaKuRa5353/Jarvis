"""Веса операций взвешенного редакционного расстояния Дамерау-Левенштейна.

Условия, при которых расстояние является метрикой (см. ``distance.py``):

    w_ins == w_del >= 0,   w_tr >= 0,   w_sub(x, y) >= 0,   w_sub(x, x) = 0

Равенство ``w_ins == w_del`` обязательно: иначе ``d(a, b) != d(b, a)`` и
нарушается аксиома симметрии. Прежние значения 0.8 / 0.9 давали квазиметрику,
которую приходилось симметризовать через ``min(d(a,b), d(b,a))`` — это удваивало
стоимость вычисления и не гарантировало неравенство треугольника.
"""

