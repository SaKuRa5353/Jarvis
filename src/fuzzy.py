"""Нечёткое исправление ошибок распознавания (Vosk).

Vosk small-ru ослышается: «тонкость» вместо «громкость», «эдип сик»
вместо «дипсик». Функция `correct()` заменяет распознанные слова
на известные триггеры команд с помощью difflib.get_close_matches
(порог 0.75).

Работает ТОЛЬКО с неизвестными словами — если слово уже в словаре,
не трогаем. Это защищает от «включи» → «выключи».
"""

import difflib

# Все однословные триггеры команд — из apps, system, web, sensors, weather.
# difflib.get_close_matches ищет именно по этому множеству.
KNOWN = frozenset((
    # — wakeword —
    "джарвис", "джервис", "jarvis",

    # — приложения —
    "проводник", "файлы", "документы", "папк",
    "вскод", "вс-код", "вс", "студия", "код", "vscode", "vs",
    "браузер", "консоль", "konsole",
    "телеграм", "тг", "телега", "ютуб", "дипсик", "дикси", "deepseek", "депсик",
    "вк", "vk",

    # — система —
    "час", "время", "дата", "число",
    "заблокируй", "блокировк", "экран",
    "звук", "громкость", "громче", "тише", "потише", "убавь",
    "скриншот", "скрин", "снимок",

    # — датчики —
    "температур", "нагрев", "перегрев", "градус", "жарит", "горяч",
    "процессор", "проц", "cpu", "цпу",
    "видеокарт", "gpu", "гпу",
    "комп", "ноут", "систем", "материн", "желез",
    "радиатор", "кулер", "вентилятор", "конденсатор",

    # — веб/поиск —
    "расписание", "почт",
    "загугли", "загуглить", "погугли", "загули", "гугл",
    "найди", "поищи",

    # — погода —
    "погод",

    # — команды-глаголы —
    "открой", "открыть", "запусти", "включи", "выключи",

    # — прочее —
    "про",
))


def correct(text: str, threshold: float = 0.70) -> str:
    """Заменяет распознанные слова на известные триггеры.

    Пример: «тонкость выше» → «громкость выше».
    Известные слова не трогаем — защищаемся от «включи» → «выключи».
    """
    words = text.split()
    if not words:
        return text

    corrected = []
    for w in words:
        if w in KNOWN:
            corrected.append(w)
        else:
            match = difflib.get_close_matches(w, KNOWN, n=1, cutoff=threshold)
            corrected.append(match[0] if match else w)
    return " ".join(corrected)
